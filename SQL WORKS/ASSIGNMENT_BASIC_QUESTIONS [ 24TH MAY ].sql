-- 35. Find highest selling category every month.
SELECT *FROM (
    SELECT MONTH(ORDER_DATE) AS MONTH_NO,CATEGORY,
	 SUM(SALES_AMOUNT) AS TOTAL_SALES,RANK() OVER(PARTITION BY MONTH(ORDER_DATE)ORDER BY SUM(SALES_AMOUNT) DESC) AS RNK
  FROM ASSIGNMENT_ecommerce_orders
    GROUP BY MONTH(ORDER_DATE), CATEGORY
) AS HIGH_SELL
