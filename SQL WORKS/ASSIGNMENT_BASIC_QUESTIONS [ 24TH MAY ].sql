-- 22. Find top 25% customers based on sales.
  SELECT *FROM (
    SELECT CUSTOMER_NAME,SUM(SALES_AMOUNT) AS TOTAL_SALES,
    NTILE(4) OVER(ORDER BY SUM(SALES_AMOUNT) DESC) AS SALES_GROUP
  FROM ASSIGNMENT_ecommerce_orders
    GROUP BY CUSTOMER_NAME
) TOP_CUSTOMERS
WHERE SALES_GROUP = 1;
        
SELECT CUSTOMER_NAME,SALES_AMOUNT ,
  NTILE(4) OVER ( ORDER BY SALES_AMOUNT DESC)  AS QUARTER_SALES
FROM ASSIGNMENT_ecommerce_orders;  
      
