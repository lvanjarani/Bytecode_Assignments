-- 45. Find highest purchase growth month-over-month.
SELECT *FROM (
    SELECT MONTH(ORDER_DATE) AS MONTH_NO,SUM(SALES_AMOUNT) AS CURRENT_MONTH_SALES,
    LAG(SUM(SALES_AMOUNT))OVER(ORDER BY MONTH(ORDER_DATE)) AS PREVIOUS_MONTH_SALES
FROM ASSIGNMENT_ecommerce_orders 
    GROUP BY MONTH(ORDER_DATE)
) AS  MONTH_OVER_MONTH
ORDER BY (CURRENT_MONTH_SALES - PREVIOUS_MONTH_SALES) DESC
LIMIT 1;

