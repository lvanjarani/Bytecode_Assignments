-- 36. Find contribution % of each order to total monthly sales.
SELECT ORDER_ID,CUSTOMER_NAME,ORDER_DATE,SALES_AMOUNT,
  SUM(SALES_AMOUNT) OVER(PARTITION BY MONTH(ORDER_DATE)) AS MONTH_TOTAL,
  ROUND(SALES_AMOUNT * 100 / SUM(SALES_AMOUNT) OVER(PARTITION BY MONTH(ORDER_DATE)),2) AS CONTRIBUTION_PERCENT
FROM ASSIGNMENT_ecommerce_orders ;

-- 37. Find customers contributing highest revenue.
SELECT *FROM (
    SELECT CUSTOMER_NAME,SUM(SALES_AMOUNT) AS TOTAL_REVENUE,
    DENSE_RANK() OVER(ORDER BY SUM(SALES_AMOUNT) DESC) AS RNK
  FROM ASSIGNMENT_ecommerce_orders 
    GROUP BY CUSTOMER_NAME
) HIGH_REVENUE
WHERE RNK = 1;

-- 38. Identify low-performing months.
   SELECT *FROM (
    SELECT MONTH(ORDER_DATE) AS MONTH_NO,SUM(SALES_AMOUNT) AS TOTAL_SALES,AVG(SUM(SALES_AMOUNT))OVER() AS AVG_MONTH_SALES
  FROM ASSIGNMENT_ecommerce_orders 
    GROUP BY MONTH(ORDER_DATE)
) LOW_PER_MONTH
WHERE TOTAL_SALES < AVG_MONTH_SALES;

-- 39. Find purchase gap between consecutive orders.
  SELECT CUSTOMER_NAME,ORDER_DATE,
   LAG(ORDER_DATE) OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREVIOUS_ORDER_DATE,
   DATEDIFF(ORDER_DATE,LAG(ORDER_DATE)OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE)) AS GAP_DAYS
  FROM ASSIGNMENT_ecommerce_orders ;

-- 40. Find customers whose sales are continuously increasing.
   SELECT * FROM (
    SELECT CUSTOMER_NAME,ORDER_DATE,SALES_AMOUNT,
    LAG(SALES_AMOUNT,1)OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREV1,
    LAG(SALES_AMOUNT,2)OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREV2
  FROM  ASSIGNMENT_ecommerce_orders
) AS CON_INCREASE
WHERE SALES_AMOUNT > PREV1
AND PREV1 > PREV2;

