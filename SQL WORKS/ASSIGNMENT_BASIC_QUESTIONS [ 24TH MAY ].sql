-- PART 1 — Basic Window Functions
-- 1. Assign row numbers for each customer based on order date.
      SELECT CUSTOMER_NAME,ORDER_DATE,
       ROW_NUMBER() OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE ) AS ROWNUB
	FROM ASSIGNMENT_ecommerce_orders;
    
-- 2. Rank customers based on highest sales amount.
      SELECT CUSTOMER_NAME,MAX(SALES_AMOUNT) AS HIGHEST_SALES,
      RANK () OVER  (ORDER BY MAX(SALES_AMOUNT)DESC ) AS RANK_NUB
	FROM ASSIGNMENT_ecommerce_orders
     GROUP BY CUSTOMER_NAME;
     
-- 3. Find dense rank of products within each category.
      SELECT PRODUCT_NAME,CATEGORY,
        DENSE_RANK () OVER ( PARTITION BY CATEGORY ORDER BY  PRODUCT_NAME) AS DENRANK 
	FROM ASSIGNMENT_ecommerce_orders;
    
-- 4. Find duplicate sales amounts using RANK() and DENSE_RANK().
    SELECT SALES_AMOUNT, COUNT(*) AS TOTAL_COUNT ,
           RANK() OVER( ORDER BY COUNT(*) DESC) AS RNK,
           DENSE_RANK() OVER( ORDER BY COUNT(*) DESC) AS DRNK
    FROM ASSIGNMENT_ecommerce_orders
GROUP BY  SALES_AMOUNT  ;

-- 5. Display previous purchase amount for every customer using LAG().
    SELECT CUSTOMER_NAME,ORDER_DATE, SALES_AMOUNT,
       LAG(SALES_AMOUNT) OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREVIOUS_SALE
	FROM ASSIGNMENT_ecommerce_orders; 
    
-- 6. Display next purchase amount using LEAD().
      SELECT CUSTOMER_NAME , ORDER_DATE,SALES_AMOUNT ,
       LEAD(SALES_AMOUNT) OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS NEXT_SALE
   FROM ASSIGNMENT_ecommerce_orders; 
   
-- 7. Find sales difference between current and previous purchase.
       SELECT CUSTOMER_NAME , ORDER_DATE,SALES_AMOUNT ,
	LAG(SALES_AMOUNT) OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREVIOUS_SALE,
    LEAD(SALES_AMOUNT) OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS NEXT_SALE,
      SALES_AMOUNT - (LAG(SALES_AMOUNT) OVER (PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE)) AS SALES_DIFF
  FROM ASSIGNMENT_ecommerce_orders; 
  
-- 8. Find percentage increase/decrease from previous purchase.
      SELECT 
    CUSTOMER_NAME,
    ORDER_DATE,
    SALES_AMOUNT,
    LAG(SALES_AMOUNT) OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE) AS PREVIOUS_SALE,
  CONCAT(ROUND(((SALES_AMOUNT - LAG(SALES_AMOUNT) OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE)) /
	LAG(SALES_AMOUNT) OVER(PARTITION BY CUSTOMER_NAME ORDER BY ORDER_DATE)) * 100,2),'%') AS PERCENTAGE_CHANGE
FROM ASSIGNMENT_ecommerce_orders;

