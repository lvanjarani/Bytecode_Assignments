-- 24. Calculate CUME_DIST() for customer sales.
       SELECT CUSTOMER_NAME , SALES_AMOUNT,
        ROUND(CUME_DIST() OVER (PARTITION BY CUSTOMER_NAME ORDER BY SALES_AMOUNT),4) AS CUME_DISTRIBUTION
     FROM ASSIGNMENT_ecommerce_orders;     
     
-- 25. Identify customers whose sales fall above 80% distribution.
    SELECT *FROM (
    SELECT CUSTOMER_NAME,SUM(SALES_AMOUNT) AS TOTAL_SALES,
	CUME_DIST() OVER( ORDER BY SUM(SALES_AMOUNT)) AS SALES_DISTRIBUTION
   FROM ASSIGNMENT_ecommerce_orders
    GROUP BY CUSTOMER_NAME
) AS SALES_FALL
WHERE SALES_DISTRIBUTION > 0.80;

