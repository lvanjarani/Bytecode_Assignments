-- 10. Calculate cumulative sales month-wise.
   SELECT MONTH(ORDER_DATE) AS MONTH_DATE,SALES_AMOUNT,
     SUM(SALES_AMOUNT) OVER(ORDER BY MONTH(ORDER_DATE)) AS CUM_SALES
  FROM ASSIGNMENT_ecommerce_orders;   
     
-- 11. Calculate rolling 3-day sales.
     SELECT ORDER_DATE, SALES_AMOUNT,
      SUM(SALES_AMOUNT) OVER (
      ORDER BY ORDER_DATE
      ROWS BETWEEN 2 PRECEDING AND CURRENT ROW ) AS ROLLING_3DAY_SALES
